"""Print what each company reports: years with Scope 1, Scope 2 (each method), Scope 3 total and categories.

Usage: python tools/availability.py [slug ...]   (writes AVAILABILITY.md when run with no arguments)
"""
import csv, os, sys
from collections import defaultdict

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def summarise(slug):
    rows = list(csv.DictReader(open(os.path.join(ROOT, "companies", slug, "emissions.csv"), encoding="utf-8")))
    have = defaultdict(set)
    cats = defaultdict(set)
    for d in rows:
        if d["status"] != "reported":
            continue
        p = d["period_label"]
        if d["scope"] == "1" and not d["scope2_method"]:
            have["Scope 1"].add(p)
        elif d["scope"] == "2":
            have[f"Scope 2 {d['scope2_method']}"].add(p)
        elif d["scope"] == "3" and d["scope3_category"] == "total":
            have["Scope 3 total"].add(p)
        elif d["scope"] == "3":
            cats[p].add(int(d["scope3_category"]))
    seg = os.path.join(ROOT, "companies", slug, "segments.csv")
    em_split = any(r["metric_type"] == "emissions" for r in csv.DictReader(open(seg, encoding="utf-8")))
    entities = sorted({d["reporting_entity"] for d in rows})
    fmt = lambda s: ", ".join(sorted(s)) if s else "none"
    return {
        "company": slug,
        "entities": "; ".join(entities) or "none",
        "Scope 1": fmt(have["Scope 1"]),
        "Scope 2 location": fmt(have["Scope 2 location"]),
        "Scope 2 market": fmt(have["Scope 2 market"]),
        "Scope 3 total": fmt(have["Scope 3 total"]),
        "Scope 3 categories": "; ".join(f"{p}: {len(c)}" for p, c in sorted(cats.items())) or "none",
        "emissions split": "yes" if em_split else "no (revenue only)",
    }


def main():
    slugs = sys.argv[1:] or sorted(d for d in os.listdir(os.path.join(ROOT, "companies")))
    out = [summarise(s) for s in slugs]
    cols = list(out[0].keys())
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(o[c] for c in cols) + " |" for o in out]
    table = "\n".join(lines)
    print(table)
    if not sys.argv[1:]:
        with open(os.path.join(ROOT, "AVAILABILITY.md"), "w", encoding="utf-8") as f:
            f.write("# What each company reports (starter data)\n\nGenerated by `python tools/availability.py`. "
                    "Years listed have a reported value; Scope 3 categories shows how many of the 15 are reported each year. "
                    "Gaps are where your team can add data.\n\n" + table + "\n")


if __name__ == "__main__":
    main()
